(* The examples of the documentation, as a program. Every block fenced ```ocaml in the files given is an example: a
   whole program, run as written. A block fenced ```output right after it is what it must print. Other fences
   (```ocaml signature, ```text, ...) are not examples. The output is the OCaml source of test/examples.exe: each
   example a local module, with line directives so that a compile error names the documentation's file and line. *)

let read_lines path =
  let ic = open_in_bin path in
  let rec go acc = match input_line ic with l -> go (l :: acc) | exception End_of_file -> close_in ic; List.rev acc in
  go []

let strip_dots p = if String.length p > 3 && String.sub p 0 3 = "../" then String.sub p 3 (String.length p - 3) else p
let fence l = String.length l >= 3 && String.sub l 0 3 = "```"
let info l = String.trim (String.sub l 3 (String.length l - 3))

(* the examples of one file: (line of the first line of code, code lines, expected output) *)
let examples path =
  let lines = Array.of_list (read_lines path) in
  let n = Array.length lines in
  let out = ref [] in
  (* the body of the fence opened at line i: its lines and the index after its closing fence *)
  let body i =
    let j = ref (i + 1) in
    while !j < n && not (fence lines.(!j)) do incr j done;
    if !j >= n then failwith (Printf.sprintf "%s:%d: a fence is never closed" path (i + 1));
    Array.to_list (Array.sub lines (i + 1) (!j - i - 1)), !j + 1
  in
  let rec scan i =
    if i < n then
      if fence lines.(i) then begin
        let code, next = body i in
        if info lines.(i) = "ocaml" then begin
          let k = ref next in
          while !k < n && String.trim lines.(!k) = "" do incr k done;
          if !k < n && fence lines.(!k) && info lines.(!k) = "output" then begin
            let expected, after = body !k in
            out := (i + 2, code, Some expected) :: !out;
            scan after
          end
          else begin
            out := (i + 2, code, None) :: !out;
            scan next
          end
        end
        else scan next
      end
      else scan (i + 1)
  in
  scan 0;
  List.rev !out

let () =
  let files = List.tl (Array.to_list Sys.argv) in
  print_string "(* generated by test/extract.ml from the documentation: do not edit *)\n\n";
  print_string "let examples : (string * int * (unit -> unit) * string option) list ref = ref []\n\n";
  List.iter
    (fun path ->
      let name = strip_dots path in
      List.iter
        (fun (line, code, expected) ->
          Printf.printf "let () =\n  let run () =\n    let module M = struct\n# %d %S\n" line name;
          List.iter (fun l -> print_string l; print_char '\n') code;
          print_string "\n    end in\n    ()\n  in\n";
          Printf.printf "  examples := (%S, %d, run, %s) :: !examples\n\n" name line
            (match expected with
             | None -> "None"
             | Some e -> Printf.sprintf "Some %S" (String.concat "\n" e)))
        (examples path))
    files;
  print_string "let () = Example_runner.run (List.rev !examples)\n"
